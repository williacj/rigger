# ABOUTME: Card #1459 (copied from #1430's, header and paths changed): turns the spike engineer's retained Claude Code session record (JSON lines) into a plain-text log of every tool
# call, with its UTC issue and completion times, the host it acted on, its exact input and its full result, redacting one account name.
import json, re, sys
src, dst = sys.argv[1], sys.argv[2]
uses, results, order = {}, {}, []
for line in open(src):
    d = json.loads(line)
    if d.get('type') not in ('assistant', 'user') or not d.get('timestamp'):
        continue
    c = d.get('message', {}).get('content')
    if not isinstance(c, list):
        continue
    for x in c:
        if x.get('type') == 'tool_use' and x['id'] not in uses:
            uses[x['id']] = (d['timestamp'], x['name'], x['input']); order.append(x['id'])
        if x.get('type') == 'tool_result':
            body = x.get('content')
            if isinstance(body, list):
                body = '\n'.join(b.get('text', '[non-text block]') if isinstance(b, dict) else str(b) for b in body)
            results[x['tool_use_id']] = (d['timestamp'], bool(x.get('is_error')), body if body is not None else '')
def host(name, inp):
    if name != 'Bash':
        return 'laptop'
    cmd = inp.get('command', '')
    if 'wsl.exe' in cmd or 'wsl-hostpc' in cmd: return 'laptop -> hostpc -> WSL'
    if 'hostpc' in cmd: return 'laptop -> hostpc'
    return 'laptop'
def redact(s):
    s = re.sub(r'MicrosoftAccount\\\S+(\s+)User(\s+)S-1-11-96-[0-9-]+', lambda m: 'MicrosoftAccount\\[redacted: account name]' + m.group(1) + 'User' + m.group(2) + 'S-1-11-96-[redacted]', s)
    s = re.sub(r'[A-Za-z0-9._%+-]+@[name withheld]', '[redacted: account name]', s)
    return s
out = ['ABOUTME: The tool calls in the #1459 spike engineer\'s retained Claude Code session record, with UTC times, host, input and the result text the record holds.', '',
       'Generated by source/gen-session-log.py from the session record of subagent a3b3356fde0abb9a6. Times are UTC: the first is when the call was issued, the second when its result returned.',
       '"host" is read from the command text: laptop unless the command reaches hostpc over ssh, and WSL when it runs wsl.exe. A command that ran in the background shows its launch result here; its output file is named in the result.',
       'Redactions: one Microsoft account name and its SID, wherever whoami /groups output appears. Nothing else is removed. A call that returned an error is marked ERROR.',
       'Scope: only calls the record holds up to the time it was generated. A result the harness saved to a file holds only a preview here, and a background command holds only its launch notice. The report, under "The transcript", lists those calls and what the log lacks.', '']
for n, i in enumerate(order, 1):
    t0, name, inp = uses[i]
    t1, err, body = results.get(i, (None, False, '[no result recorded: the session record ends before it]'))
    shown = inp.get('command') if name == 'Bash' and set(inp) <= {'command', 'description', 'timeout', 'run_in_background', 'dangerouslyDisableSandbox'} else json.dumps(inp, ensure_ascii=False, indent=1)
    extra = '' if name != 'Bash' else '  ' + json.dumps({k: v for k, v in inp.items() if k != 'command'}, ensure_ascii=False)
    out.append(f'### {n}. {t0} -> {t1}  host={host(name, inp)}  tool={name}{"  ERROR" if err else ""}{extra}')
    out.append(redact(shown if isinstance(shown, str) else str(shown)))
    out.append('--- result ---')
    out.append(redact(str(body)))
    out.append('')
open(dst, 'w').write('\n'.join(out))
print(len(order), 'calls')
